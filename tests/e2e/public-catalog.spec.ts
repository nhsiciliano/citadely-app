import { mkdirSync, readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";

const reviewDir = ".impeccable/review/catalog";

test("galería pública: visor completo y retorno del foco", async ({ page }) => {
  await page.goto("/b/citadely-demo-ux");
  const gallery = page.getByRole("region", { name: "Galería de Consultorios Horizonte" });
  await expect(gallery).toBeVisible();
  const trigger = gallery.getByRole("button", { name: /Ampliar imagen 1 de 1/ });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "Galería de Consultorios Horizonte" });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole("img", { name: /imagen 1 de 1/ })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Cerrar imagen completa" })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
  await expect(trigger).toBeFocused();
  await expect(gallery.locator(".public-gallery-side, .public-gallery-dot-button, .public-gallery-arrow")).toHaveCount(0);
});

test("catálogo público: explorar, cancelar, elegir y conservar horario", async ({ page }) => {
  await page.goto("/b/citadely-demo-ux#reservar");
  await expect(page.getByText("Elegí un servicio para ver días y horarios disponibles.", { exact: true })).toBeVisible();
  const card = page.getByRole("button", { name: "Ver detalle de Consulta inicial", exact: true });
  await card.click();
  const dialog = page.getByRole("dialog", { name: "Consulta inicial", exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText("Primera evaluación y definición del plan de atención.")).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Cerrar detalle del servicio" })).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(dialog.getByRole("button", { name: "Elegir este servicio" })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
  await expect(card).toBeFocused();
  await expect(page.locator(".public-service-card-selected")).toHaveCount(0);
  await card.click();
  await page.mouse.click(1, 1);
  await expect(dialog).toBeHidden();
  await card.click();
  await dialog.getByRole("button", { name: "Elegir este servicio" }).click();
  await expect(page.getByRole("heading", { name: "Elegí día y horario" })).toBeFocused();
  await expect(page.locator(".public-service-card-selected")).toContainText("Consulta inicial");
  await expect(page.locator(".public-booking-day:enabled").first()).toBeVisible();
  await expect(page.locator(".public-booking-day[aria-pressed='true']")).toHaveCount(1);
  const hour = page.locator('.public-booking-time[aria-label$="disponible"]:enabled').first();
  await hour.click();
  const summary = page.locator("form > section").last();
  const selectedSummary = await summary.innerText();
  await page.getByRole("button", { name: "Ver detalle de Consulta inicial, seleccionado" }).click();
  await dialog.getByRole("button", { name: "Elegir este servicio" }).click();
  expect(await summary.innerText()).toBe(selectedSummary);
  await page.getByRole("button", { name: "Ver detalle de Control clínico", exact: true }).click();
  await page.keyboard.press("Escape");
  expect(await summary.innerText()).toBe(selectedSummary);
  await page.getByRole("button", { name: "Ver detalle de Control clínico", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Elegir este servicio" }).click();
  await expect(summary).toContainText("Control clínico");
  await expect(summary).toContainText("Elegí día y horario");

  let submitted: Record<string, unknown> | undefined;
  await page.route("**/api/public-booking", async (route) => {
    submitted = route.request().postDataJSON();
    await route.fulfill({ json: { amount_cents: 0, status: "confirmed" } });
  });
  await page.locator('.public-booking-time[aria-label$="disponible"]:enabled').first().click();
  await page.getByLabel("Nombre y apellido").fill("Cliente de prueba visual");
  await page.getByLabel("Email", { exact: true }).fill("prueba@example.com");
  await page.getByLabel("Teléfono").fill("1199887766");
  await page.getByRole("button", { name: "Confirmar reserva" }).click();
  await expect(page.getByText(/Reserva confirmada\. Te enviamos/)).toBeVisible();
  expect(submitted?.serviceId).toBeTruthy();
  expect(submitted?.startsAt).toBeTruthy();
});

for (const width of [1440, 390]) {
  test(`catálogo y modal responsive ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 960 });
    await page.goto("/b/citadely-demo-ux#reservar");
    const track = page.getByRole("region", { name: "Servicios disponibles" });
    const dimensions = await track.evaluate((element) => ({ width: element.clientWidth, card: element.firstElementChild!.getBoundingClientRect().width, overflow: element.scrollWidth > element.clientWidth }));
    expect(dimensions.overflow).toBe(true);
    if (width > 1024) expect(dimensions.card / dimensions.width).toBeCloseTo(1 / 3, 1);
    else expect(dimensions.card / dimensions.width).toBeCloseTo(.86, 1);
    await page.getByRole("button", { name: "Ver servicio siguiente" }).click();
    await expect.poll(() => track.evaluate((element) => element.scrollLeft)).toBeGreaterThan(100);
    await page.getByRole("button", { name: "Ver servicio anterior" }).click();
    await expect.poll(() => track.evaluate((element) => element.scrollLeft)).toBeLessThan(5);
    await track.focus();
    await page.keyboard.press("ArrowRight");
    await expect.poll(() => track.evaluate((element) => element.scrollLeft)).toBeGreaterThan(100);
    await page.getByRole("button", { name: "Ver servicio anterior" }).click();
    await expect.poll(() => track.evaluate((element) => element.scrollLeft)).toBeLessThan(5);
    mkdirSync(reviewDir, { recursive: true });
    await page.locator("form").scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${reviewDir}/public-${width}.png` });
    await page.getByRole("button", { name: "Ver detalle de Consulta inicial", exact: true }).click();
    await expect(page.getByRole("dialog")).toBeVisible();
    await expect.poll(() => page.getByRole("dialog").evaluate((element) => element.getAnimations().length)).toBe(0);
    await page.screenshot({ path: `${reviewDir}/modal-${width}.png` });
    const action = page.getByRole("dialog").getByRole("button", { name: "Elegir este servicio" });
    const box = await action.boundingBox();
    expect(box!.height).toBeGreaterThanOrEqual(44);
    expect(box!.y + box!.height).toBeLessThanOrEqual(960);
    await page.keyboard.press("Escape");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const question = page.getByRole("button", { name: "¿Cómo solicito mi turno?", exact: true });
    await expect(question).toHaveAttribute("aria-expanded", "true");
    await expect(page.getByText("Elegí un servicio y uno de los horarios disponibles.", { exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: "Hacer una consulta" })).toHaveAttribute("href", /^https:\/\/wa\.me\/5491123456789/);
    await expect.poll(() => page.locator(".public-faq-answer-open").evaluate((element) => element.getAnimations().length)).toBe(0);
    await page.screenshot({ path: `${reviewDir}/faq-${width}.png` });
    await question.click();
    await expect(page.getByText("Elegí un servicio y uno de los horarios disponibles.", { exact: true })).toBeHidden();
    await page.emulateMedia({ reducedMotion: "reduce" });
    await question.click();
    expect(await page.locator(".public-faq-answer").evaluate((element) => Math.max(...getComputedStyle(element).transitionDuration.split(",").map(parseFloat)))).toBeLessThanOrEqual(.001);
  });
}

test("vista previa reutiliza catálogo y preguntas sin reservar", async ({ page }) => {
  const env = readFileSync(".env.local", "utf8");
  const value = (name: string) => env.split(/\r?\n/).find((line) => line.startsWith(`${name}=`))?.slice(name.length + 1) ?? "";
  test.skip(!value("CITADELY_DEMO_EMAIL"), "Requiere cuenta demo local.");
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(value("CITADELY_DEMO_EMAIL"));
  await page.getByRole("textbox", { name: "Contraseña", exact: true }).fill(value("CITADELY_DEMO_PASSWORD"));
  await page.getByRole("button", { name: "Ingresar" }).click();
  await expect(page).toHaveURL(/\/negocio/);
  await page.goto("/negocio/pagina-publica");
  const preview = page.getByRole("region", { name: "Vista previa de la página pública", exact: true });
  await preview.getByRole("button", { name: "Ver detalle de Consulta inicial", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Elegir este servicio" }).click();
  await expect(preview.locator(".public-service-card-selected")).toContainText("Consulta inicial");
  await expect(preview.getByRole("heading", { name: "Elegí día y horario", exact: true })).toBeFocused();
  await expect(preview.getByRole("button", { name: "¿Cómo solicito mi turno?", exact: true })).toHaveAttribute("aria-expanded", "true");
  await expect(preview.getByText("Elegí un servicio y uno de los horarios disponibles.", { exact: true })).toBeVisible();
  await expect.poll(() => preview.locator(".public-faq-answer-open").evaluate((element) => element.getAnimations().length)).toBe(0);
  const previewGallery = preview.getByRole("region", { name: "Galería de Consultorios Horizonte" });
  await previewGallery.getByRole("button", { name: /Ampliar imagen/ }).click();
  await expect(page.getByRole("dialog", { name: "Galería de Consultorios Horizonte" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(previewGallery.getByRole("button", { name: /Ampliar imagen/ })).toBeFocused();
  await page.screenshot({ path: `${reviewDir}/preview-faq-desktop.png` });
  await preview.locator(".public-service-track").scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${reviewDir}/preview-desktop.png` });
  await page.setViewportSize({ width: 390, height: 960 });
  await preview.getByRole("button", { name: "Ver detalle de Consulta inicial, seleccionado" }).click();
  await expect(page.getByRole("dialog").getByRole("button", { name: "Elegir este servicio" })).toBeVisible();
  await page.keyboard.press("Escape");
  await page.screenshot({ path: `${reviewDir}/preview-mobile.png` });
});
